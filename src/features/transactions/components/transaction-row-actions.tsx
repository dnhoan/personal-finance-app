"use client";
import * as React from "react";
import { useRouter } from "next/navigation";
import type { Route } from "next";
import { MoreVertical, Pencil, Trash2 } from "lucide-react";
import {
  DropdownMenu,
  DropdownMenuTrigger,
  DropdownMenuContent,
  DropdownMenuItem,
} from "@/components/ui/dropdown-menu";
import { EditInstanceDialog } from "@/features/recurring/components/edit-instance-dialog";
import { detachInstance } from "@/features/recurring/actions";
import type { TxLedgerItem } from "../queries";
import { toEditableTx, type TxEditOptions } from "../lib/to-editable-tx";
import { TransactionEditSheet } from "./transaction-edit-sheet";

// Per-row menu: Edit + Delete. Edit is hidden only for a transfer whose
// counterpart can't be resolved (broken pair). A row generated by a recurring
// rule routes Edit through a 2-mode dialog (this-instance-only vs. edit-series)
// before reaching the normal edit sheet. Delete is owned by the parent row (it
// drives optimistic removal + the undo toast); this just invokes `onDelete`.
export function TransactionRowActions({
  tx,
  editOptions,
  onDelete,
}: {
  tx: TxLedgerItem;
  editOptions: TxEditOptions;
  onDelete: () => void;
}) {
  const router = useRouter();
  const [editOpen, setEditOpen] = React.useState(false);
  const [instanceOpen, setInstanceOpen] = React.useState(false);
  const editable = React.useMemo(() => toEditableTx(tx), [tx]);
  const isRecurring = tx.recurringRuleId !== null;

  function handleEdit() {
    if (isRecurring) setInstanceOpen(true);
    else setEditOpen(true);
  }

  // "This only": detach from the rule, then edit as a normal row.
  async function handleEditThisOnly() {
    setInstanceOpen(false);
    await detachInstance({ transactionId: tx.id });
    setEditOpen(true);
  }

  // "Edit series": jump to the rule's edit sheet on the recurring page.
  function handleEditSeries() {
    setInstanceOpen(false);
    router.push(`/recurring?edit=${tx.recurringRuleId}` as Route);
  }

  return (
    <>
      <DropdownMenu>
        <DropdownMenuTrigger
          aria-label="Tùy chọn giao dịch"
          className="flex h-9 w-9 items-center justify-center rounded-md text-fg-subtle hover:bg-surface-muted focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
        >
          <MoreVertical size={18} aria-hidden="true" />
        </DropdownMenuTrigger>
        <DropdownMenuContent align="end">
          {editable && (
            <DropdownMenuItem onSelect={handleEdit}>
              <Pencil size={16} aria-hidden="true" /> Sửa
            </DropdownMenuItem>
          )}
          <DropdownMenuItem
            className="text-expense"
            onSelect={(e) => {
              e.preventDefault();
              onDelete();
            }}
          >
            <Trash2 size={16} aria-hidden="true" /> Xóa
          </DropdownMenuItem>
        </DropdownMenuContent>
      </DropdownMenu>

      {isRecurring && editable && (
        <EditInstanceDialog
          open={instanceOpen}
          onOpenChange={setInstanceOpen}
          onEditThisOnly={handleEditThisOnly}
          onEditSeries={handleEditSeries}
        />
      )}

      {editable && (
        <TransactionEditSheet
          tx={editable}
          options={editOptions}
          open={editOpen}
          onOpenChange={setEditOpen}
        />
      )}
    </>
  );
}
